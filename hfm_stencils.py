def combine_stencils(stencils=STENCILS):
    """Sum identical positive offsets, preserving first-occurrence ordering."""
    result = []
    for stencil in stencils:
        combined = {}
        for dx, dy, dtheta, weight in stencil:
            if weight > 0:
                key = dx, dy, dtheta
                combined[key] = combined.get(key, 0.0) + weight
        result.append([(*offset, weight) for offset, weight in combined.items()])
    return result


COMBINED_STENCILS = combine_stencils()
